"""Решение уравнения."""

MAX_VALUE = 10000


def проверить_предел(имя, значение):
    "Если модуль значения больше MAX_VALUE — возбудить ошибку."
    if abs(значение) > MAX_VALUE:
        raise ValueError(f"коэффициент {имя} вне допустимого диапазона")


def проверить_коэффициенты(коэффициенты):
    "Проверка всех коэффициентов."
    for имя, значение in коэффициенты.items():
        проверить_предел(имя, значение)


def solve(a, b, c):
    """
    Решает уравнение a*x^2 + b*x + c = 0.
    Возвращает: вид уравнения, дискриминант, список корней.
    """
    if a == 0 and b == 0:
        raise ValueError("это не уравнение")

    if a == 0:
        # линейное
        x = -c / b
        return "линейное", None, [x]

    # квадратное
    d = b * b - 4 * a * c
    if d > 0:
        sqrt_d = d ** 0.5
        x1 = (-b + sqrt_d) / (2 * a)
        x2 = (-b - sqrt_d) / (2 * a)
        if x1 < x2:
            x1, x2 = x2, x1
        return "квадратное", d, [x1, x2]
    if d == 0:
        x = -b / (2 * a)
        return "квадратное", d, [x]
    return "квадратное", d, []
