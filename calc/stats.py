"""Показатели последовательности."""

import math

MAX_COUNT = 20
MAX_ABS = 10000


def сумма(числа):
    результат = 0.0
    for число in числа:
        результат = результат + число
    return результат


def среднее(числа):
    return сумма(числа) / len(числа)


def сумма_квадратов(числа):
    результат = 0.0
    for число in числа:
        результат = результат + число ** 2
    return результат


def среднее_квадратическое(числа):
    return math.sqrt(сумма_квадратов(числа) / len(числа))


def сумма_квадратов_отклонений(числа):
    среднее_значение = среднее(числа)
    результат = 0.0
    for число in числа:
        результат = результат + (число - среднее_значение) ** 2
    return результат


def дисперсия(числа):
    return сумма_квадратов_отклонений(числа) / len(числа)


def ско(числа):
    return math.sqrt(дисперсия(числа))


def стандартное_отклонение(числа):
    if len(числа) < 2:
        return None
    return math.sqrt(сумма_квадратов_отклонений(числа) / (len(числа) - 1))


def минимум(числа):
    результат = числа[0]
    for число in числа:
        if число < результат:
            результат = число
    return результат


def максимум(числа):
    результат = числа[0]
    for число in числа:
        if число > результат:
            результат = число
    return результат


def количество_положительных(числа):
    результат = 0
    for число in числа:
        if число > 0:
            результат = результат + 1
    return результат


def количество_отрицательных(числа):
    результат = 0
    for число in числа:
        if число < 0:
            результат = результат + 1
    return результат


